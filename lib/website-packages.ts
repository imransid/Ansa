import website from "@/core/internal/packages/website.json";
import type { AnsaPackage } from "@/lib/types/packages";

// The free trial and the packages as the public website shows them (step
// 58), read from core's website.json: core's test keeps that file equal to
// core/internal/packages/packages.go, the one place names, prices and limits
// live (make website-packages writes it again). The website asks core
// nothing: it is fully static.
export const WEBSITE_PACKAGES = website as { trialDays: number; trial: AnsaPackage; paid: AnsaPackage[] };

// The lowest monthly price, for "from $10 a month".
export function lowestMonthlyPrice(): number {
  return Math.min(...WEBSITE_PACKAGES.paid.map((pkg) => pkg.priceUsd));
}
