// hasGlyph: whether the font can write this character.
func hasGlyph(letter rune) bool {
	_, known := glyphRows[letter]
	return known
}

// glyph is one character's rows, top first.
func glyph(letter rune) []string {
	return strings.Fields(glyphRows[letter])
}
